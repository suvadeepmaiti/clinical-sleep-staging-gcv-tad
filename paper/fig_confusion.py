"""Fig. 2 (row-normalized test confusion matrices, EEG+EOG students) and N1-recall macros for the text.

Reads slides/deck_data.json (built from the result files by slides/deck_data.py): confusion matrices summed over the
10 test folds. Writes figs/confusion.pdf and figs/confusion_numbers.tex (\\nrecall{cohort}{model}, % of scorer N1).
"""
import sys
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(next(p for p in Path(__file__).resolve().parents if (p / "src" / "repo_paths.py").exists()) / "src"))
import repo_paths  # noqa: E402  (data/results locations; puts the cohort modelling folders on sys.path)
D = json.loads((repo_paths.ANALYSIS / "deck_data.json").read_text())["results"]
STAGES = ["W", "N1", "N2", "N3", "R"]
COHORT = "isleeps"


def matrices(c):
    r = D[c]
    return {"ce": np.array(r["confusion"]["eeg_eog_ce"], float), "gtad_cv": np.array(r["confusion"]["eeg_eog_gtad_cv"], float),
            "ce_full": np.array(r["full_detail"]["eeg_eog"]["confusion"], float)}


def main():
    plt.rcParams.update({"font.family": "serif", "font.serif": ["STIXGeneral", "DejaVu Serif"],
                         "mathtext.fontset": "stix", "font.size": 7})
    mats = matrices(COHORT)
    titles = {"ce": "CE, 25% labels", "gtad_cv": r"G$_{cv}$-TAD, 25% labels", "ce_full": "CE, 100% labels"}
    fig, axes = plt.subplots(1, 3, figsize=(3.45, 1.42), sharey=True)
    for ax, (k, M) in zip(axes, mats.items()):
        P = 100 * M / M.sum(1, keepdims=True)
        ax.imshow(P, cmap="Blues", vmin=0, vmax=100)
        for i in range(5):
            for j in range(5):
                ax.text(j, i, f"{P[i, j]:.0f}", ha="center", va="center", fontsize=5.6,
                        color="white" if P[i, j] > 55 else "black",
                        fontweight="bold" if (i, j) == (1, 1) else "normal")
        ax.add_patch(plt.Rectangle((-0.5, 0.5), 5, 1, fill=False, ec="#C0392B", lw=0.9))
        ax.set_title(titles[k], fontsize=6.6, pad=2)
        ax.set_xticks(range(5), STAGES, fontsize=5.8)
        ax.set_yticks(range(5), STAGES, fontsize=5.8)
        ax.tick_params(length=0, pad=1)
        ax.set_xlabel("predicted", fontsize=5.8, labelpad=1)
        for s in ax.spines.values():
            s.set_visible(False)
    axes[0].set_ylabel("scorer", fontsize=5.8, labelpad=1)
    fig.subplots_adjust(left=0.07, right=0.995, top=0.88, bottom=0.17, wspace=0.08)
    (HERE / "figs").mkdir(exist_ok=True)
    fig.savefig(HERE / "figs/confusion.pdf")
    plt.close(fig)

    lines = ["% generated by fig_confusion.py: N1 recall (% of scorer N1 epochs), EEG+EOG students, 10 test folds pooled",
             r"\newcommand{\nrecall}[2]{\csname nrec@#1@#2\endcsname}"]
    for c in D:
        for k, M in matrices(c).items():
            lines.append(rf"\expandafter\def\csname nrec@{c}@{k}\endcsname{{{100 * M[1, 1] / M[1].sum():.0f}}}")
    (HERE / "figs/confusion_numbers.tex").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[2:]))


if __name__ == "__main__":
    main()
