"""Fig. (hypnodensity, paper version of slides/fig_hypnodensity.png) and its macros.

One iSLEEPS fold-1 test patient (the representative patient of slides/deck_data.json, median G_cv-TAD - CE gain),
EEG+EOG students at 25% labels, saved test softmax outputs. Writes figs/hypnodensity.pdf and figs/hypno_numbers.tex
(\\hypno{model}{acc|low}: accuracy and % of epochs below 0.6 confidence on that night).
"""
import json
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(next(p for p in Path(__file__).resolve().parents if (p / "src" / "repo_paths.py").exists()) / "src"))
import repo_paths  # noqa: E402  (data/results locations; puts the cohort modelling folders on sys.path)
sys.path.insert(0, str(repo_paths.REPO / "analysis"))
from xai_calibration import LOW, STAGE_COL, INK, MUTED, ordered_labels  # noqa: E402

LOW_CONF = 0.6


def main():
    plt.rcParams.update({"font.family": "serif", "font.serif": ["STIXGeneral", "DejaVu Serif"],
                         "mathtext.fontset": "stix", "font.size": 7})
    pat = json.loads((repo_paths.ANALYSIS / "deck_data.json").read_text())["prediction_example"]["patient"]
    fold = LOW["isleeps"] / "fold_01"
    test = json.loads((fold / "test_metrics.json").read_text())["test_subjects"]
    y, subj, _ = ordered_labels("isleeps")
    mask = np.isin(subj, test)
    sel = subj[mask] == pat
    ys = y[mask][sel]
    t = np.arange(sel.sum()) * 30 / 3600
    rows = [("ce", "CE"), ("gtad_cv", r"G$_{cv}$-TAD")]
    fig, ax = plt.subplots(3, 1, figsize=(3.45, 2.3), sharex=True, gridspec_kw={"height_ratios": [1, 1, 1]})
    ax[0].step(t, np.array([4, 2, 1, 0, 3])[ys], where="post", color=INK, lw=0.6)
    ax[0].set_yticks([0, 1, 2, 3, 4], ["N3", "N2", "N1", "R", "W"])
    ax[0].set_ylim(-0.4, 4.4)
    ax[0].set_title("(a) Scorer hypnogram", loc="left", fontsize=7, pad=3)
    nums = {}
    for a, (k, name), letter in zip(ax[1:], rows, "bc"):
        p = np.load(fold / "eeg_eog" / f"{k}_test_prob.npy")[sel]
        a.stackplot(t, p.T[[3, 2, 1, 4, 0]], colors=[STAGE_COL[i] for i in (3, 2, 1, 4, 0)], step="post", lw=0)
        low = p.max(1) < LOW_CONF
        a.scatter(t[low], np.full(low.sum(), 1.07), s=4, color="#C0392B", marker="|", lw=0.4, clip_on=False)
        a.set_ylim(0, 1)
        a.set_yticks([0, 0.5, 1], ["0", ".5", "1"])
        acc = 100 * (p.argmax(1) == ys).mean()
        nums[k] = {"acc": f"{acc:.0f}", "low": f"{100 * low.mean():.0f}"}
        a.set_title(f"({letter}) {name} student, 25% labels (acc. {acc:.0f}%)", loc="left", fontsize=7, pad=5)
    for a in ax:
        for s in ("top", "right"):
            a.spines[s].set_visible(False)
        a.spines["left"].set_linewidth(0.5)
        a.spines["bottom"].set_linewidth(0.5)
        a.tick_params(colors=MUTED, labelsize=6, width=0.5, length=2)
    ax[-1].set_xlabel("Hours from recording start", labelpad=1)
    handles = [plt.Rectangle((0, 0), 1, 1, color=STAGE_COL[i]) for i in (0, 4, 1, 2, 3)]
    handles.append(plt.Line2D([], [], color="#C0392B", marker="|", ls="none", markersize=5))
    ax[-1].legend(handles, ["W", "REM", "N1", "N2", "N3", f"conf. < {LOW_CONF}"], ncol=6, frameon=False, fontsize=5.8,
                  loc="upper center", bbox_to_anchor=(0.5, -0.55), handlelength=0.9, columnspacing=0.8,
                  handletextpad=0.3)
    fig.subplots_adjust(left=0.09, right=0.99, top=0.93, bottom=0.2, hspace=0.6)
    for ext, kw in (("pdf", {}), ("png", {"dpi": 300})):
        fig.savefig(HERE / f"figs/hypnodensity.{ext}", bbox_inches="tight", pad_inches=0.02, **kw)
    plt.close(fig)
    lines = ["% generated by fig_hypnodensity.py: iSLEEPS fold-1 test patient, EEG+EOG students at 25% labels",
             f"% patient: {pat}; low = % of epochs with top-class probability < {LOW_CONF}",
             r"\newcommand{\hypno}[2]{\csname hypno@#1@#2\endcsname}"]
    lines += [rf"\expandafter\def\csname hypno@{k}@{m}\endcsname{{{v}}}" for k, d in nums.items() for m, v in d.items()]
    (HERE / "figs/hypno_numbers.tex").write_text("\n".join(lines) + "\n")
    print(pat, nums)


if __name__ == "__main__":
    main()
